"""Provider-agnostic renderer.

The base class owns the shared file contract (``versions.tf``, ``providers.tf``,
``main.tf``, ``.gitignore``) and the ``terraform`` block scaffolding. Provider
renderers implement resource/provider blocks and may override any hook whose
semantics differ between providers.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Generic, TypeVar

from python_tofu.core.exceptions import RenderError
from python_tofu.core.hcl import Attr, Block, attr, body, render
from python_tofu.core.models import BackendConfig, BaseStack
from python_tofu.core.results import RenderResult

StackT = TypeVar("StackT", bound=BaseStack)

GITIGNORE = """\
# Generated by python-tofu
.terraform/
*.tfstate
*.tfstate.*
*.tfplan
crash.log
crash.*.log
"""


class BaseRenderer(ABC, Generic[StackT]):
    """Write a provider stack to OpenTofu files in a working directory."""

    MANAGED_FILES = ("versions.tf", "providers.tf", "main.tf", ".gitignore")
    GITIGNORE = GITIGNORE

    def __init__(self, workdir: str | Path) -> None:
        self.workdir = Path(workdir)

    # ── provider hooks ────────────────────────────────────────────────
    @abstractmethod
    def resource_blocks(self, stack: StackT) -> list[Block]:
        """Return every top-level ``resource`` block, in a stable order."""

    @abstractmethod
    def provider_blocks(self, stack: StackT) -> list[Block]:
        """Return the provider configuration block(s)."""

    def data_blocks(self, stack: StackT) -> list[Block]:
        """Return top-level ``data`` blocks (default: none)."""

        return []

    def required_providers(self, stack: StackT) -> dict[str, dict[str, str]]:
        """Map provider name → ``required_providers`` attributes."""

        return {}

    def output_blocks(self, stack: StackT) -> list[Block]:
        """Return top-level ``output`` blocks, rendered after resources."""

        return [
            Block(
                "output",
                (item.name,),
                body(
                    Attr("value", item.value),
                    attr("description", item.description),
                    attr("sensitive", True) if item.sensitive else None,
                ),
            )
            for item in stack.outputs
        ]

    def backend_block(self, stack: StackT) -> Block | None:
        """Render a generic ``backend`` block, or override for typed backends."""

        backend = stack.backend
        if not isinstance(backend, BackendConfig):
            return None
        return Block(
            "backend",
            (backend.kind,),
            body(*(Attr(key, value) for key, value in backend.settings.items())),
        )

    # ── shared rendering ──────────────────────────────────────────────
    def terraform_block(self, stack: StackT) -> Block:
        required = self.required_providers(stack)
        required_block = None
        if required:
            required_block = Block(
                "required_providers",
                body=tuple(Attr(name, spec) for name, spec in required.items()),
            )
        return Block(
            "terraform",
            body=body(
                Attr("required_version", stack.required_version),
                required_block,
                self.backend_block(stack),
            ),
        )

    def _extra_files(self, stack: StackT) -> dict[str, str]:
        """Validate and return the stack's raw-HCL escape-hatch files."""

        extra = dict(stack.extra_files)
        for name in extra:
            target = Path(name)
            if target.name != name or name in ("", ".", ".."):
                raise RenderError(f"extra_files name must be a flat file name: {name!r}")
            if name in self.MANAGED_FILES:
                raise RenderError(
                    f"extra_files may not override managed file {name!r}; "
                    f"managed files are {', '.join(self.MANAGED_FILES)}"
                )
            if not (name.endswith(".tf") or name.endswith(".tf.json")):
                raise RenderError(f"extra_files must end in .tf or .tf.json, got {name!r}")
        return extra

    def render_text(self, stack: StackT) -> dict[str, str]:
        """Return the generated file contents without touching the filesystem."""

        data = self.data_blocks(stack)
        blocks = self.resource_blocks(stack)
        outputs = self.output_blocks(stack)
        main = (
            render(*data, *blocks, *outputs)
            if (data or blocks or outputs)
            else "# No resources declared in the stack.\n"
        )
        contents = {
            "versions.tf": render(self.terraform_block(stack)),
            "providers.tf": render(*self.provider_blocks(stack)),
            "main.tf": main,
            ".gitignore": self.GITIGNORE,
        }
        contents.update(self._extra_files(stack))
        return contents

    def render(self, stack: StackT) -> RenderResult:
        """Write every managed file into :attr:`workdir`."""

        contents = self.render_text(stack)
        self.workdir.mkdir(parents=True, exist_ok=True)

        files: list[Path] = []
        for name, text in contents.items():
            target = self.workdir / name
            temporary = target.with_name(target.name + ".tmp")
            temporary.write_text(text, encoding="utf-8")
            temporary.replace(target)
            files.append(target)

        return RenderResult(
            workdir=self.workdir,
            files=tuple(files),
            resources=len(self.resource_blocks(stack)),
        )
