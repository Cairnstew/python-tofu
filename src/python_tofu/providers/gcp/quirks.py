"""GCP-specific rules that would be wrong to bake into the core.

Identifier shapes, role syntax and resource-name conventions are GCP quirks.
Keeping them here means another provider can define completely different rules
without fighting a generic validator.
"""

from __future__ import annotations

import mimetypes
import re

from python_tofu.core.exceptions import RenderError
from python_tofu.core.hcl import is_reference_template

# GCP identifiers are stricter than "any non-empty string"; validating early
# turns a mid-apply API error into a local traceback.
PROJECT_ID_RE = re.compile(r"^[a-z][a-z0-9-]{4,28}[a-z0-9]$")
BUCKET_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9._-]{1,61}[a-z0-9]$")
SERVICE_ACCOUNT_ID_RE = re.compile(r"^[a-z][a-z0-9-]{4,28}[a-z0-9]$")
CLOUD_RUN_SERVICE_NAME_RE = re.compile(r"^[a-z](?:[a-z0-9-]{0,47}[a-z0-9])?$")
CLOUD_FUNCTION_NAME_RE = re.compile(r"^[a-z](?:[a-z0-9-]{0,61}[a-z0-9])?$")
ENV_VAR_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
CLOUD_RUN_MEMORY_RE = re.compile(r"^[0-9]+(?:Mi|Gi)$")
FUNCTION_MEMORY_RE = re.compile(r"^[0-9]+(?:k|M|G|Mi|Gi)?$")
TIMEOUT_RE = re.compile(r"^[0-9]+(?:\.[0-9]+)?s$")
SECRET_NAME_RE = re.compile(r"^[A-Za-z0-9_-]{1,255}$")
ARTIFACT_REPO_ID_RE = re.compile(r"^[a-z][a-z0-9._-]{1,62}$")
VOLUME_NAME_RE = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$")
PUBSUB_NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9._~+%-]{2,254}$")


def validate_role(role: str) -> str:
    """Accept predefined roles (``roles/...``), project custom roles or a reference."""

    if is_reference_template(role):
        return role
    if not (role.startswith("roles/") or "/roles/" in role):
        raise ValueError(
            f"role must be a predefined role (roles/...) or a project custom role: {role!r}"
        )
    return role


def literal_identifier(value: str, field: str, *, reason: str) -> str:
    """Reject an HCL interpolation in a field that becomes an address or label.

    A computed value in such a field would be mangled by ``slug()`` and the
    resource address would silently change. Nix-authored stacks have no
    :class:`~python_tofu.core.hcl.Raw`, so the error explains the alternative.
    """

    if is_reference_template(value):
        raise ValueError(
            f"{field} must be a literal, not an HCL interpolation ({value!r}); "
            f"{reason} Move the computed part into an attribute or an `output`."
        )
    return value


def slug(value: str) -> str:
    """Turn arbitrary text into a valid Terraform resource-name fragment."""

    result = re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")
    if not result:
        result = "resource"
    if result[0].isdigit():
        result = f"r_{result}"
    return result


def guess_content_type(name: str, default: str = "application/octet-stream") -> str:
    """Guess an object's content type from its key, falling back to bytes."""

    guessed, _encoding = mimetypes.guess_type(name)
    return guessed or default


def require_unique(seen: dict[str, str], address: str, source: str) -> None:
    """Reject two resources that collapse to the same HCL address."""

    if address in seen:
        raise RenderError(
            f"duplicate resource address {address!r} generated by {source!r}; "
            f"it collides with {seen[address]!r}. Give the resources distinct names."
        )
    seen[address] = source
